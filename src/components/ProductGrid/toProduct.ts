import {
  ModelVariation,
  Product,
  StockEntry,
} from "@/interfaces/products.interface";

/** Os diálogos de produto avulso recebem um Product completo */
export const entryToProduct = (e: StockEntry): Product => ({
  id: e.product_id!,
  category_id: e.category_id,
  name: e.name,
  description: e.description,
  barcode: e.barcode,
  quantity: e.quantity,
  size: e.size,
  category_name: e.category_name,
  cost_price: e.min_cost_price,
  sale_price: e.min_sale_price,
  created_by: "",
  updated_by: "",
  deleted_by: null,
  created_at: e.created_at,
  updated_at: e.created_at,
  deleted_at: null,
  sell_in_bulk: e.sell_in_bulk,
  unit: e.unit,
  total_registered: e.total_registered,
  total_sold: e.total_sold,
});

export const variationToProduct = (v: ModelVariation): Product => ({
  id: v.id,
  category_id: v.category_id,
  name: v.name,
  description: v.description,
  barcode: v.barcode,
  quantity: v.quantity,
  size: v.size,
  category_name: v.category_name,
  cost_price: v.cost_price,
  sale_price: v.sale_price,
  created_by: "",
  updated_by: "",
  deleted_by: null,
  created_at: v.created_at,
  updated_at: v.created_at,
  deleted_at: null,
  sell_in_bulk: v.sell_in_bulk,
  unit: v.unit,
  total_registered: v.total_registered,
  total_sold: v.total_sold,
  model_name: v.model_name,
  color: v.color,
});
